"""Small end-to-end fleet for the README quickstart, CI and the tests.

Builds two small simulated fleets (Aido Rover v0.2 and the synthetic Fari
profile) with the same code paths as the full Week 2-3 data: simulator ->
Week 1 ingestion -> hourly as-of features. Then writes a pipeline config that
points at them, so ``release.train``, ``pipeline.publish`` and the pipeline run
on the small fleet exactly as on the full one.

    python -m ingen_fleet_health.release.quickstart --root data/quickstart          # data + config
    python -m ingen_fleet_health.release.quickstart --root data/quickstart --all    # + train, publish, backfill

Everything it writes is synthetic and git-ignored.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import timedelta
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from ingen_fleet_health.config import REPO_ROOT, load_config
from ingen_fleet_health.contract import platform_profile
from ingen_fleet_health.features.build import build_feature_table
from ingen_fleet_health.simulate.fleet import simulate_fleet_v02

PLATFORM_CONFIGS = {"aido_rover": REPO_ROOT / "configs" / "aido_rover_v0_2.yaml",
                    "fari": REPO_ROOT / "configs" / "fari.yaml"}
# Seeds of the small quickstart fleet. With 12 units a random seed often has no
# fault onset in the training window, and a model cannot be trained; these seeds
# were picked (by onset counts only, before any model was fitted) so that the
# fit, validation and scoring windows each contain at least two onsets on both
# platforms. The quickstart fleet demonstrates the plumbing; it is not an evaluation.
DEFAULT_SEEDS = {"aido_rover": 79, "fari": 1098}


def prepare_platform(root: Path, platform: str, units: int, days: int, seed: int) -> dict[str, Any]:
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    from ingest_pipeline import run_pipeline

    cfg_path = PLATFORM_CONFIGS[platform]
    out = root / "sources" / platform
    manifest = simulate_fleet_v02(out, units, days, seed, cfg_path)
    config = load_config(cfg_path)
    report = run_pipeline(out / "generated" / "fleet_telemetry.csv", out_root=out, profile=platform_profile(config))
    telemetry = pd.read_parquet(out / "data" / "validated" / "telemetry.parquet")
    maintenance = pd.read_csv(out / "events" / "maintenance_events.csv")
    table = build_feature_table(telemetry, maintenance, config, pd.Timestamp(manifest["start_utc"]),
                                pd.Timestamp(manifest["end_utc"]))
    (out / "features").mkdir(parents=True, exist_ok=True)
    table.to_parquet(out / "features" / "features_hourly.parquet", index=False)
    return {"platform": platform, "units": units, "days": days, "seed": seed,
            "fault_onsets": manifest["fault_events_with_onset_in_run"], "accepted_rows": report["accepted_rows"],
            "feature_rows": len(table)}


def write_config(root: Path, cutoff_day: int, validation_days: int, seed: int = 0) -> Path:
    base = yaml.safe_load((REPO_ROOT / "configs" / "pipeline.yaml").read_text(encoding="utf-8"))
    base["data_root"] = str((root / "w04").resolve())
    base["platforms"] = {p: {"config": str(PLATFORM_CONFIGS[p]), "source_dir": str((root / "sources" / p).resolve())}
                         for p in PLATFORM_CONFIGS}
    base["release_training"].update({"cutoff_day": cutoff_day, "validation_days": validation_days, "seed": seed})
    path = root / "pipeline.yaml"
    path.write_text("# generated by ingen_fleet_health.release.quickstart (synthetic quickstart fleet)\n"
                    + yaml.safe_dump(base, sort_keys=False), encoding="utf-8")
    return path


def build(root: Path, units: int, days: int, cutoff_day: int, validation_days: int,
          seeds: dict[str, int] | None = None) -> tuple[Path, list[dict[str, Any]]]:
    root.mkdir(parents=True, exist_ok=True)
    seeds = seeds or DEFAULT_SEEDS
    info = [prepare_platform(root, p, units, days, seeds[p]) for p in PLATFORM_CONFIGS]
    return write_config(root, cutoff_day, validation_days), info


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the small quickstart fleet (synthetic)")
    parser.add_argument("--root", type=Path, default=REPO_ROOT / "data" / "quickstart")
    parser.add_argument("--units", type=int, default=12)
    parser.add_argument("--days", type=int, default=40)
    parser.add_argument("--cutoff-day", type=int, default=24)
    parser.add_argument("--validation-days", type=int, default=4)
    parser.add_argument("--all", action="store_true", help="also train + register, publish and backfill")
    args = parser.parse_args()
    root = args.root.resolve()
    cfg, info = build(root, args.units, args.days, args.cutoff_day, args.validation_days)
    print(json.dumps(info, indent=2))
    print(f"pipeline config: {cfg}")
    if not args.all:
        return
    os.environ["FLEET_PIPELINE_CONFIG"] = str(cfg)
    from ingen_fleet_health.pipeline.publish import publish_platform
    from ingen_fleet_health.pipeline.runner import backfill
    from ingen_fleet_health.pipeline.settings import load_settings
    from ingen_fleet_health.release import train

    sys.argv = ["train", "--config", str(cfg)]
    train.main()
    settings = load_settings(cfg)
    for p in settings.platforms:
        publish_platform(settings, p)
    start = pd.Timestamp(json.loads((root / "sources" / "aido_rover" / "simulation_manifest.json")
                                    .read_text(encoding="utf-8"))["start_utc"]).date()
    first, last = start, start + timedelta(days=args.days - 1)
    score_from = start + timedelta(days=args.cutoff_day)
    backfill(settings, first, score_from - timedelta(days=1), steps=("ingest", "features"))   # history load
    backfill(settings, score_from, last)
    print(f"backfill done {first} .. {last} (scored from {score_from}); "
          f"dashboard: FLEET_PIPELINE_CONFIG={cfg} streamlit run dashboard/app.py")


if __name__ == "__main__":
    main()
